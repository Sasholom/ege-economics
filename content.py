from fractions import Fraction as F

def fmt(v, dec=2):
    v = round(float(v), dec)
    s = f"{v:,.{dec}f}".rstrip('0').rstrip('.')
    return s.replace(',', ' ').replace('.', ',')

def tex(v, dec=2):
    return fmt(v, dec).replace(',', '{,}').replace(' ', r'\,')

def years_table(S, r, x, unit='Год'):
    rows = [['0', '', '', '$' + tex(S) + '$']]
    k, b = 0, 1 + r / 100
    while S > 1e-9:
        k += 1
        D = S * b
        pay = min(D, x)
        S = D - pay
        rows.append([str(k), f'${tex(D/b)}\\cdot {tex(b,4)} = {tex(D)}$', '$' + tex(pay) + '$', '$' + tex(S) + '$'])
    return ([unit, 'Долг с %', 'Платёж', 'Остаток'], rows), k

def ann_table(pays, unit='Год'):
    """Символьная таблица: долг S, коэффициент b, платежи pays (строки LaTeX)."""
    rows = [['0', '', '', '$S$']]
    after = 'S'
    terms = []  # слагаемые с x после каждого шага
    n = len(pays)
    for k, p in enumerate(pays, 1):
        withp = f'Sb' if k == 1 else f'({after})\\,b'
        # пересчитать «после платежа»
        terms = [t + 'b' if t else 'b' for t in terms]  # домножили на b
        terms = [fix(t) for t in terms]
        terms.append('')
        powS = 'Sb' if k == 1 else f'Sb^{k}'
        parts = []
        for t, pp in zip(terms, pays[:k]):
            coef = pp
            parts.append(f'{coef}{t}' if t else coef)
        after_new = powS + ''.join(' - ' + q for q in parts)
        rows.append([str(k), f'${withp}$', f'${p}$', '$0$' if k == n else f'${after_new}$'])
        after = after_new
    return ([unit, 'Долг с %', 'Платёж', 'Остаток'], rows)

def fix(t):
    # 'bb' -> 'b^2', 'bbb' -> 'b^3'
    c = t.count('b')
    return '' if c == 0 else ('b' if c == 1 else f'b^{c}')

